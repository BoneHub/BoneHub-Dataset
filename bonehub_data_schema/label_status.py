"""How a label's segmentation, mesh or NURBS file came to be, and what checks it has had.

SubjectInfo.segmentation, .mesh and .nurbs each map a BoneLabelMap name to a status. A
status answers two independent questions, so it is stored as a two-digit integer:

    status = origin * 10 + review

    origin - who produced the file              review - the strongest check so far
    0  not available                            0  not reviewed
    1  BoneHub, fully automatic                 1  automatic check passed
    2  BoneHub, created or corrected by a human 2  automatic check failed
    3  original source dataset                  3  reviewed by human expert, accepted
    4  original source, corrected by BoneHub    4  reviewed by human expert, rejected

So 33 is a source segmentation an expert verified, and 14 is a fully automatic BoneHub
segmentation an expert rejected. Every combination is valid. With origin 0 the review is
a check of the absence itself: 03 means an expert confirmed the structure is not there,
and 04 means an expert found it present but not yet segmented.

The same status type serves segmentations, meshes and NURBS.
"""

from enum import IntEnum


class _DescribedCode(IntEnum):
    """An integer code that carries a human-readable description."""

    def __new__(cls, value: int, description: str):
        member = int.__new__(cls, value)
        member._value_ = value
        member.description = description
        return member


class Origin(_DescribedCode):
    """Who produced the file."""

    NOT_AVAILABLE = 0, "not available"
    BONEHUB_AUTOMATIC = 1, "generated by BoneHub, fully automatic"
    BONEHUB_HUMAN_EDITED = 2, "generated by BoneHub, created or corrected by a human"
    SOURCE = 3, "from the original source dataset"
    SOURCE_CORRECTED = 4, "from the original source dataset, corrected by BoneHub"


class Review(_DescribedCode):
    """The strongest check the file has had so far.

    Codes rise with the authority of the check (none, automatic, human expert), so when a
    file passes an automatic check and an expert then accepts it, record the expert.
    """

    NOT_REVIEWED = 0, "not reviewed"
    AUTOMATIC_PASSED = 1, "automatic check passed"
    AUTOMATIC_FAILED = 2, "automatic check failed"
    EXPERT_ACCEPTED = 3, "reviewed by human expert, accepted"
    EXPERT_REJECTED = 4, "reviewed by human expert, rejected"

    @property
    def is_failure(self) -> bool:
        return self in (Review.AUTOMATIC_FAILED, Review.EXPERT_REJECTED)


class LabelStatus(int):
    """A status code that knows what it means.

    It is a plain int (origin * 10 + review), so it is stored and compared as a number,
    but constructing one validates the code and exposes its parts:

        LabelStatus.of(Origin.SOURCE, Review.EXPERT_ACCEPTED)   # 33
        LabelStatus(14).review                                  # Review.EXPERT_REJECTED
        LabelStatus(14).is_usable                               # False
    """

    def __new__(cls, code: int):
        # bool is an int subclass, and JSON true must not slip through as status 1
        if isinstance(code, bool) or not isinstance(code, int):
            raise ValueError(f"A label status must be an integer, got {code!r}.")
        origin, review = divmod(code, 10)
        if code < 0 or origin not in Origin._value2member_map_ or review not in Review._value2member_map_:
            raise ValueError(
                f"Invalid label status {code}. A status is origin*10 + review, with origin in "
                f"{[int(o) for o in Origin]} and review in {[int(r) for r in Review]}; "
                "see bonehub_data_schema/label_status.py."
            )
        return super().__new__(cls, code)

    @classmethod
    def of(cls, origin: Origin, review: Review = Review.NOT_REVIEWED) -> "LabelStatus":
        return cls(int(origin) * 10 + int(review))

    @classmethod
    def all(cls) -> list["LabelStatus"]:
        """Every valid status, in code order."""
        return [cls.of(origin, review) for origin in Origin for review in Review]

    @property
    def origin(self) -> Origin:
        return Origin(int(self) // 10)

    @property
    def review(self) -> Review:
        return Review(int(self) % 10)

    @property
    def is_available(self) -> bool:
        """A file exists for this label, whatever its review."""
        return self.origin is not Origin.NOT_AVAILABLE

    @property
    def is_usable(self) -> bool:
        """A file exists and has not failed review."""
        return self.is_available and not self.review.is_failure

    @property
    def is_missing(self) -> bool:
        """No file, but a check found the structure present, so one still needs producing."""
        return not self.is_available and self.review.is_failure

    def describe(self) -> str:
        text = f"{self.origin.description}; {self.review.description}"
        if not self.is_available and self.review is not Review.NOT_REVIEWED:
            text += " (structure is present)" if self.review.is_failure else " (confirmed absent)"
        return text
