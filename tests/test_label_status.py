import unittest

from bonehub_data_schema import LabelStatus, Origin, Review, SubjectInfo


class TestLabelStatus(unittest.TestCase):
    def test_code_is_origin_times_ten_plus_review(self):
        status = LabelStatus.of(Origin.SOURCE, Review.EXPERT_ACCEPTED)
        self.assertEqual(status, 33)
        self.assertIs(LabelStatus(33).origin, Origin.SOURCE)
        self.assertIs(LabelStatus(33).review, Review.EXPERT_ACCEPTED)
        self.assertEqual(LabelStatus.of(Origin.BONEHUB_AUTOMATIC), 10)

    def test_every_combination_is_valid(self):
        codes = LabelStatus.all()
        self.assertEqual(len(codes), len(Origin) * len(Review))
        self.assertIn(4, codes)  # not available, but an expert found the structure present

    def test_invalid_codes_are_rejected(self):
        for bad in (55, 5, 50, -1, 100, True, "30", None, 3.0):
            with self.subTest(bad=bad), self.assertRaises(ValueError):
                LabelStatus(bad)

    def test_availability_and_usability(self):
        cases = {
            # code: (is_available, is_usable, is_missing)
            0: (False, False, False),  # not available, not reviewed
            3: (False, False, False),  # expert confirmed absent
            4: (False, False, True),  # expert found it present: still needs producing
            10: (True, True, False),  # BoneHub automatic, not reviewed
            12: (True, False, False),  # BoneHub automatic, automatic check failed
            14: (True, False, False),  # BoneHub automatic, expert rejected
            33: (True, True, False),  # source, expert accepted
        }
        for code, expected in cases.items():
            status = LabelStatus(code)
            with self.subTest(code=code):
                self.assertEqual((status.is_available, status.is_usable, status.is_missing), expected)

    def test_describe_explains_checks_of_an_absence(self):
        self.assertIn("confirmed absent", LabelStatus(3).describe())
        self.assertIn("structure is present", LabelStatus(4).describe())
        self.assertEqual(
            LabelStatus(14).describe(), "generated by BoneHub, fully automatic; reviewed by human expert, rejected"
        )

    def test_review_codes_rise_with_authority(self):
        self.assertLess(Review.NOT_REVIEWED, Review.AUTOMATIC_PASSED)
        self.assertLess(max(Review.AUTOMATIC_PASSED, Review.AUTOMATIC_FAILED), Review.EXPERT_ACCEPTED)


class TestSubjectInfoStatuses(unittest.TestCase):
    def test_one_status_type_serves_segmentation_mesh_and_nurbs(self):
        subject = SubjectInfo(image=True)
        for setter in (subject.set_segmentation_value, subject.set_mesh_value, subject.set_nurbs_value):
            setter("FEMUR_LEFT", LabelStatus.of(Origin.SOURCE))
            setter("FEMUR_RIGHT", LabelStatus.of(Origin.NOT_AVAILABLE, Review.EXPERT_ACCEPTED))
            setter("TIBIA_LEFT", LabelStatus.of(Origin.BONEHUB_AUTOMATIC, Review.EXPERT_REJECTED))
        for kind in ("segmentation", "mesh", "nurbs"):
            with self.subTest(kind=kind):
                self.assertEqual(subject.available_labels(kind), ["FEMUR_LEFT", "TIBIA_LEFT"])
                self.assertEqual(subject.usable_labels(kind), ["FEMUR_LEFT"])

    def test_statuses_are_stored_as_plain_ints(self):
        subject = SubjectInfo(image=True)
        subject.set_segmentation_value("FEMUR_LEFT", LabelStatus(33))
        self.assertIs(type(subject.segmentation["FEMUR_LEFT"]), int)


if __name__ == "__main__":
    unittest.main()
